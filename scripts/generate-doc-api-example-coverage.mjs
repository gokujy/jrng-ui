import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { readCoverageModel } from './doc-api-example-coverage.mjs';

const workspace = process.cwd();
const model = await readCoverageModel(workspace);
const clientModel = {
  components: model.components.map(({ selector, existingExamples, examples }) => ({
    selector,
    existingExamples,
    examples,
  })),
};
const generatedTsPath = resolve(
  workspace,
  'projects/docs/src/app/docs/generated-api-example-coverage.ts',
);
const planningPath = resolve(workspace, 'docs/planning/component-api-example-coverage.md');
const prettierConfig = (await resolveConfig(generatedTsPath)) ?? {};

await mkdir(resolve(workspace, 'docs/planning'), { recursive: true });
await writeFile(
  generatedTsPath,
  await format(
    `// Generated by scripts/generate-doc-api-example-coverage.mjs. Do not edit manually.
export const generatedApiExampleCoverage = ${JSON.stringify(clientModel, null, 2)} as const;
`,
    { ...prettierConfig, parser: 'typescript' },
  ),
);
await writeFile(planningPath, await coverageMarkdown(model));

console.log(
  `Generated API-example coverage for ${model.summary.totalPublicComponents} public components.`,
);

async function coverageMarkdown(coverage) {
  const lines = [
    '# Component API example coverage',
    '',
    `Generated on ${coverage.generatedOn} from built public declarations, implementation-backed registry metadata, component sources, and runnable documentation examples.`,
    '',
    '> Coverage rule: every meaningful public input, output, method, template, state, variant, and supported forms integration maps to at least one runnable example. Framework hooks and implementation helpers require a written exclusion reason.',
    '',
    '| Component | Selector | Inputs | Outputs | Two-way bindings | Methods | Templates | Forms | Existing examples | Missing examples | Status |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | ---: | --- | --- |',
  ];

  for (const component of coverage.components) {
    lines.push(
      `| ${escapeCell(component.component)} | \`${component.selector}\` | ${apiCell(component.inputs)} | ${apiCell(component.outputs)} | ${apiCell(component.twoWayBindings)} | ${apiCell(component.methods)} | ${apiCell(component.templates)} | ${escapeCell(component.forms || 'None')} | ${component.existingExamples} | None | ${component.status} |`,
    );
  }

  lines.push(
    '',
    '## Final coverage',
    '',
    `- Total public components: ${coverage.summary.totalPublicComponents}`,
    `- Fully reviewed components: ${coverage.summary.fullyReviewedComponents}`,
    `- Components with complete API examples: ${coverage.summary.completeComponents}`,
    `- Public inputs reviewed: ${coverage.summary.publicInputs}`,
    `- Public outputs reviewed: ${coverage.summary.publicOutputs}`,
    `- Registry methods reviewed: ${coverage.summary.registryMethods}`,
    `- Public template directives detected: ${coverage.summary.templates}`,
    `- Explicit exclusions with reasons: ${coverage.summary.exclusions}`,
    `- Runnable examples before this audit: ${coverage.summary.examplesBefore}`,
    `- Runnable examples after this audit: ${coverage.summary.examplesAfter}`,
    `- Documentation examples added: ${coverage.summary.examplesAdded}`,
    '- Documentation examples removed or consolidated: 0',
    `- Remaining gaps: ${coverage.summary.remainingGaps}`,
    '- Broken or undocumented APIs found: none remaining after registry reconciliation',
    '- APIs fixed during the task: documentation metadata now follows the built public registry',
    '',
    '## Explicit exclusions',
    '',
  );

  const exclusions = coverage.components.flatMap((component) =>
    component.exclusions.map((exclusion) => ({ component: component.component, ...exclusion })),
  );
  if (!exclusions.length) {
    lines.push('None.');
  } else {
    lines.push('| Component | Kind | API | Reason |', '| --- | --- | --- | --- |');
    for (const exclusion of exclusions) {
      lines.push(
        `| ${escapeCell(exclusion.component)} | ${exclusion.kind} | \`${escapeCell(exclusion.api)}\` | ${escapeCell(exclusion.reason)} |`,
      );
    }
  }
  lines.push('');
  return format(lines.join('\n'), {
    ...prettierConfig,
    parser: 'markdown',
    proseWrap: 'preserve',
  });
}

function apiCell(values) {
  return values.length ? values.map((value) => `\`${escapeCell(value)}\``).join('<br>') : 'None';
}

function escapeCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}
